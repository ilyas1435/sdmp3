#!/data/data/com.termux/files/usr/bin/env bash
# sdmp3 installer / updater for Termux.
#
#   curl -fsSL https://raw.githubusercontent.com/ilyas1435/sdmp3/main/install.sh | bash
#   bash install.sh                  # install or update
#   bash install.sh --uninstall      # remove the command (keeps your data)
#   bash install.sh --uninstall --purge   # also delete the installed source
#
# Environment overrides:
#   SDMP3_HOME   install directory   (default: ~/.local/share/sdmp3)
#   SDMP3_REPO   git remote          (default: https://github.com/ilyas1435/sdmp3.git)
#   SDMP3_BIN    command path        (default: $PREFIX/bin/sdmp3)
#
# NOTE: this script must stay heredoc-free - it is meant to be piped into bash,
# and a heredoc would swallow the rest of the script from stdin.

set -eu

REPO_URL="${SDMP3_REPO:-https://github.com/ilyas1435/sdmp3.git}"
SDMP3_HOME="${SDMP3_HOME:-$HOME/.local/share/sdmp3}"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m  ok\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m  !\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m  x\033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- environment
[ -n "${PREFIX:-}" ] && [ -d "$PREFIX/bin" ] || die "this installer is for Termux (no \$PREFIX found)."
BIN="${SDMP3_BIN:-$PREFIX/bin/sdmp3}"

if [ "${1:-}" = "--uninstall" ] || [ "${1:-}" = "uninstall" ]; then
    if [ -f "$BIN" ]; then
        rm -f "$BIN"
        ok "removed command $BIN"
    else
        warn "command $BIN was not installed"
    fi
    if [ "${2:-}" = "--purge" ]; then
        rm -rf "$SDMP3_HOME"
        ok "removed source $SDMP3_HOME"
    else
        printf '  source kept in %s (run: bash install.sh --uninstall --purge)\n' "$SDMP3_HOME"
    fi
    printf '  state/logs kept in %s\n' "$HOME/.local/state/sdmp3"
    exit 0
fi

# ------------------------------------------------------------- system packages
missing=""
for bin in python git; do
    command -v "$bin" >/dev/null 2>&1 || missing="$missing $bin"
done
command -v ffmpeg >/dev/null 2>&1 || missing="$missing ffmpeg"

if [ -n "$missing" ]; then
    if command -v pkg >/dev/null 2>&1; then
        say "installing Termux packages:$missing"
        # shellcheck disable=SC2086
        pkg install -y $missing
    else
        warn "missing packages:$missing (pkg not found - install them manually)"
    fi
fi

PYTHON="$(command -v python || command -v python3 || true)"
[ -n "$PYTHON" ] || die "python is not installed (pkg install python)"

# ------------------------------------------------------------------- get code
if [ -d "$SDMP3_HOME/.git" ]; then
    git config --global --add safe.directory "$SDMP3_HOME" >/dev/null 2>&1 || true
    branch="$(git -C "$SDMP3_HOME" rev-parse --abbrev-ref HEAD 2>/dev/null || echo main)"
    [ "$branch" = "HEAD" ] && branch=main
    if [ -n "$(git -C "$SDMP3_HOME" status --porcelain 2>/dev/null)" ]; then
        warn "local edits in $SDMP3_HOME - keeping them"
        git -C "$SDMP3_HOME" pull --ff-only || warn "could not fast-forward; resolve manually"
    else
        say "updating existing install ($branch)"
        git -C "$SDMP3_HOME" fetch --depth 1 origin "$branch"
        git -C "$SDMP3_HOME" reset --hard FETCH_HEAD >/dev/null
    fi
elif [ -d "$SDMP3_HOME" ] && [ -n "$(ls -A "$SDMP3_HOME" 2>/dev/null || true)" ]; then
    die "$SDMP3_HOME exists but is not a git checkout. Move it away or set SDMP3_HOME."
else
    say "cloning $REPO_URL"
    mkdir -p "$(dirname "$SDMP3_HOME")"
    git clone --depth 1 "$REPO_URL" "$SDMP3_HOME"
fi

[ -f "$SDMP3_HOME/project.py" ] || die "install is corrupt (project.py missing) - delete $SDMP3_HOME and retry"

# ------------------------------------------------------------ python packages
say "checking Python dependencies"
if "$PYTHON" -m pip --version >/dev/null 2>&1; then
    if ! "$PYTHON" -m pip install --quiet --upgrade -r "$SDMP3_HOME/requirements.txt"; then
        warn "some Python packages failed to install (audio index / TTS may not work)"
    fi
else
    warn "pip is unavailable - run: pkg install python-pip"
fi

# ------------------------------------------------------------------- command
say "writing command $BIN"
mkdir -p "$(dirname "$BIN")"
printf '#!%s/bin/sh\n# generated by sdmp3 install.sh - do not edit (re-run install.sh instead)\nexec "%s" "%s" "$@"\n' \
    "$PREFIX" "$PYTHON" "$SDMP3_HOME/sdmp3_cli.py" > "$BIN"
chmod 755 "$BIN"
"$BIN" version >/dev/null 2>&1 || die "installed command failed to run - try: $BIN doctor"

# ------------------------------------------------------------------- summary
printf '\n'
say "sdmp3 $("$PYTHON" -c "print(open('$SDMP3_HOME/VERSION').read().strip())" 2>/dev/null || echo installed)"
printf '  source:  %s\n' "$SDMP3_HOME"
printf '  command: %s\n' "$BIN"
printf '\n'
printf '  sdmp3                 start the web UI (Ctrl+C to stop)\n'
printf '  sdmp3 start           run it in the background\n'
printf '  sdmp3 status          show pid, port and URLs\n'
printf '  sdmp3 update          pull the latest version from GitHub\n'
printf '  sdmp3 doctor          check the environment\n'
printf '\n'
printf '  then open http://localhost:5050 (or http://<device-ip>:5050)\n\n'
